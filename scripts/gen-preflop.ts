/**
 * Builds data/preflop.json: win/tie/loss counts for each of the 169 starting hands against one
 * random hand, by seeded Monte Carlo (MVP §5). Run from the repo root:
 *
 *   npx --yes tsx@4.20.6 scripts/gen-preflop.ts
 *
 * The output depends only on SEED, SAMPLES and the code it calls, so running it again gives the
 * same file. `--samples=N` and `--out=PATH` override the defaults, for quick trial runs.
 */
import { mkdirSync, writeFileSync } from "node:fs";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";
import { STARTING_HANDS, simulateStartingHand } from "../src/ai/slider/startingHands";

const SEED = 20261031;
const SAMPLES = 50_000;
const COMMAND = "npx --yes tsx@4.20.6 scripts/gen-preflop.ts";

const arg = (name: string) => process.argv.find((a) => a.startsWith(`--${name}=`))?.split("=")[1];
const samples = Number(arg("samples") ?? SAMPLES);
const out = resolve(arg("out") ?? fileURLToPath(new URL("../data/preflop.json", import.meta.url)));

const start = performance.now();
const rows = STARTING_HANDS.map((hand, index) => {
  const counts = simulateStartingHand(index, samples, SEED);
  process.stdout.write(`\r${index + 1}/${STARTING_HANDS.length} ${hand}    `);
  return `    ${JSON.stringify({ hand, ...counts })}`;
});

const header = {
  about:
    "Preflop win/tie/loss counts against one random hand, one entry per starting hand. " +
    "Generated by seeded Monte Carlo; these are estimates. Trusted data (see MVP section 5).",
  command: COMMAND,
  rng: "seededRng (mulberry32) from src/engine/cards.ts; entry i uses seed + i; deals as in sampledCounts (src/ai/slider/counts.ts)",
  seed: SEED,
  samplesPerHand: samples,
};
const head = JSON.stringify(header, null, 2).slice(0, -2); // drop the closing "\n}"
mkdirSync(dirname(out), { recursive: true });
writeFileSync(out, `${head},\n  "hands": [\n${rows.join(",\n")}\n  ]\n}\n`);
console.log(`\nWrote ${out} in ${((performance.now() - start) / 1000).toFixed(1)} s`);
