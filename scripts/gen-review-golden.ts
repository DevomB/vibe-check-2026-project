/**
 * Builds engine/Engine/ReviewGolden.lean: river reviews computed by the TypeScript reference
 * (`reviewRiverDecision` in src/review/review.ts), so the Lean `reviewRiver` can be checked
 * against it. Run from the repo root:
 *
 *   npx --yes tsx@4.20.6 scripts/gen-review-golden.ts
 *
 * The Lean file is generated. Never edit it by hand; run this again. The same SEED always gives
 * the same file.
 */
import { writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";
import { type Card, fullDeck, seededRng } from "../src/engine/cards";
import { type RiverSpot, botRiverRange, reviewRiverDecision } from "../src/review/review";

const SEED = 20261031;
const RANDOM_CASES = 24;
const BIG_BLIND = 10;
const COMMAND = "npx --yes tsx@4.20.6 scripts/gen-review-golden.ts";
const leanPath = fileURLToPath(new URL("../engine/Engine/ReviewGolden.lean", import.meta.url));

const rng = seededRng(SEED);
const int = (lo: number, hi: number) => lo + Math.floor(rng() * (hi - lo + 1));
const cards = (s: string) => s.split(" ") as Card[];

/** Seven different cards: five for the board, then the human's two. */
function randomCards(): Card[] {
  const deck = fullDeck();
  for (let k = 0; k < 7; k++) {
    const j = int(k, deck.length - 1);
    [deck[k], deck[j]] = [deck[j]!, deck[k]!];
  }
  return deck.slice(0, 7);
}

function randomSpot(): RiverSpot {
  const all = randomCards();
  const before = 10 * int(2, 40);
  const toCall = 10 * int(1, 40);
  return {
    board: all.slice(0, 5),
    hole: all.slice(5, 7),
    pot: before + toCall,
    toCall,
    // Sometimes fewer chips than the bet, so the part the human cannot match goes back.
    stack: rng() < 0.25 ? int(1, toCall) : int(toCall, 500),
    bigBlind: BIG_BLIND,
    bluffPct: int(0, 60),
  };
}

/** Hand-picked spots: the nut straight, a weak pair, a short stack, and a board every hand ties. */
const edgeCases: RiverSpot[] = [
  { board: cards("2c 7d Js Qh 9s"), hole: cards("Kc Td"), pot: 150, toCall: 50, stack: 400, bigBlind: BIG_BLIND, bluffPct: 33 },
  { board: cards("2c 7d Js Qh 9s"), hole: cards("3h 2d"), pot: 200, toCall: 100, stack: 400, bigBlind: BIG_BLIND, bluffPct: 33 },
  { board: cards("2c 7d Js Qh 9s"), hole: cards("3h 2d"), pot: 200, toCall: 100, stack: 400, bigBlind: BIG_BLIND, bluffPct: 60 },
  { board: cards("2c 7d Js Qh 9s"), hole: cards("Kc Td"), pot: 200, toCall: 100, stack: 30, bigBlind: BIG_BLIND, bluffPct: 0 },
  { board: cards("As Ks Qs Js Ts"), hole: cards("2c 3d"), pot: 300, toCall: 100, stack: 400, bigBlind: BIG_BLIND, bluffPct: 33 },
];

function leanCase(spot: RiverSpot): string {
  const call = reviewRiverDecision(spot, "call");
  const fold = reviewRiverDecision(spot, "fold");
  const frac = (f: { num: number; den: number }) => `⟨${f.num}, ${f.den}⟩`;
  const { wins, ties, losses } = call.counts;
  return (
    `  ⟨${JSON.stringify(spot.board.join(" "))}, ${JSON.stringify(spot.hole.join(" "))}, ` +
    `${spot.pot}, ${spot.toCall}, ${spot.stack}, ${spot.bluffPct},\n` +
    `    ${JSON.stringify(call.label)}, ${JSON.stringify(fold.label)}, ${frac(call.worthBb.call)}, ` +
    `${frac(call.equityHad)}, ${frac(call.equityNeeded)}, ⟨${wins}, ${ties}, ${losses}⟩⟩`
  );
}

const randomCases: RiverSpot[] = [];
while (randomCases.length < RANDOM_CASES) {
  const spot = randomSpot();
  // The TypeScript refuses a spot where the human's cards block every hand the bot bets.
  if (botRiverRange(spot).length > 0) randomCases.push(spot);
}
const allCases = [...edgeCases, ...randomCases];

const lean = `-- Generated by scripts/gen-review-golden.ts from the TypeScript river review. Do not edit by hand.
-- To rebuild, run from the repo root: ${COMMAND}
import Engine.Equity
import Engine.Review

/-!
# Golden cases for the river review (generated)

River reviews computed by the TypeScript reference \`reviewRiverDecision\`
(\`src/review/review.ts\`): hand-picked spots first, then random ones from seed ${SEED}.
\`Engine/ReviewTests.lean\` checks that the Lean \`reviewRiver\` gives the same grades.
-/

/-- A river spot and the TypeScript review of calling and of folding there. -/
structure ReviewGoldenCase where
  /-- The five board cards, as text: \`"2c 7d Js Qh 9s"\`. -/
  board : String
  /-- The human's two cards, as text. -/
  hole : String
  pot : Nat
  toCall : Nat
  stack : Nat
  bluffPct : Nat
  /-- The label for calling, as the screen shows it. -/
  callLabel : String
  /-- The label for folding. -/
  foldLabel : String
  /-- What calling was worth, in big blinds. -/
  worthCall : Frac
  equityHad : Frac
  equityNeeded : Frac
  /-- How many of the bot's possible hands the human beats, ties and loses to. -/
  counts : Counts

/-- ${edgeCases.length} hand-picked cases, then ${RANDOM_CASES} random ones. -/
def reviewGoldenCases : List ReviewGoldenCase := [
${allCases.map(leanCase).join(",\n")}
]
`;

writeFileSync(leanPath, lean);
console.log(`Wrote ${allCases.length} cases to ${leanPath}`);
