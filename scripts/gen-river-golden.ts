/**
 * Builds engine/Engine/RiverGolden.lean: river betting sets chosen by the TypeScript reference
 * (`riverBettingSet` in src/review/riverStrategy.ts), so the Lean port can be checked against it
 * hand for hand. Run from the repo root:
 *
 *   npx --yes tsx@4.20.6 scripts/gen-river-golden.ts
 *
 * The Lean file is generated. Never edit it by hand; run this again. The same SEED always gives
 * the same file.
 *
 * For each board and Bluff setting, the file holds the role of every candidate hand, in the
 * order of `riverCandidates`: one letter per hand, v (value), b (bluff) or c (check).
 */
import { writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";
import { type Card, fullDeck, seededRng } from "../src/engine/cards";
import { riverBettingSet, riverCandidates } from "../src/review/riverStrategy";

const SEED = 20261031;
const RANDOM_CASES = 20;
const COMMAND = "npx --yes tsx@4.20.6 scripts/gen-river-golden.ts";
const leanPath = fileURLToPath(new URL("../engine/Engine/RiverGolden.lean", import.meta.url));

const rng = seededRng(SEED);
const int = (lo: number, hi: number) => lo + Math.floor(rng() * (hi - lo + 1));

function randomBoard(): Card[] {
  const deck = fullDeck();
  for (let k = 0; k < 5; k++) {
    const j = int(k, deck.length - 1);
    [deck[k], deck[j]] = [deck[j]!, deck[k]!];
  }
  return deck.slice(0, 5);
}

const cards = (s: string) => s.split(" ") as Card[];

/** Hand-picked boards: no flush possible, a royal flush on the board (every hand ties), four
 * of a kind on the board, and a paired board with three hearts. Each at the edges of Bluff. */
const edgeCases: { board: Card[]; bluffPct: number }[] = [
  ...[0, 1, 33, 50, 60].map((bluffPct) => ({ board: cards("2c 7d Js Qh 9s"), bluffPct })),
  ...[0, 33, 60].map((bluffPct) => ({ board: cards("As Ks Qs Js Ts"), bluffPct })),
  { board: cards("9c 9d 9h 9s 2c"), bluffPct: 40 },
  { board: cards("5h 5c 8h Kh 2d"), bluffPct: 25 },
];

function leanCase({ board, bluffPct }: { board: Card[]; bluffPct: number }): string {
  const { value, bluffs } = riverBettingSet(board, bluffPct);
  const role = new Map<string, string>();
  for (const h of value) role.set(h.cards.join(" "), "v");
  for (const h of bluffs) role.set(h.cards.join(" "), "b");
  const roles = riverCandidates(board)
    .map((h) => role.get(h.join(" ")) ?? "c")
    .join("");
  return `  ⟨${JSON.stringify(board.join(" "))}, ${bluffPct}, ${value.length}, ${bluffs.length},\n    ${JSON.stringify(roles)}⟩`;
}

const randomCases = Array.from({ length: RANDOM_CASES }, () => ({ board: randomBoard(), bluffPct: int(0, 60) }));
const allCases = [...edgeCases, ...randomCases];

const lean = `-- Generated by scripts/gen-river-golden.ts from the TypeScript river betting set. Do not edit by hand.
-- To rebuild, run from the repo root: ${COMMAND}

/-!
# Golden cases for the river betting set (generated)

River betting sets chosen by the TypeScript reference \`riverBettingSet\`
(\`src/review/riverStrategy.ts\`): hand-picked boards first, then random ones from seed ${SEED}.
\`Engine/RiverTests.lean\` checks that the Lean \`riverBettingSet\` picks the same hands.
-/

/-- A river board, a Bluff setting, and the betting set the TypeScript picks there. -/
structure RiverGoldenCase where
  /-- The five board cards, as text: \`"2c 7d Js Qh 9s"\`. -/
  board : String
  bluffPct : Nat
  /-- How many value hands the TypeScript picks. -/
  valueCount : Nat
  /-- How many bluff hands the TypeScript picks. -/
  bluffCount : Nat
  /-- The role of each candidate hand, in the order of \`riverCandidates\`: \`v\` (value),
  \`b\` (bluff) or \`c\` (check). -/
  roles : String
  deriving Inhabited

/-- ${edgeCases.length} hand-picked cases, then ${RANDOM_CASES} random ones. -/
def riverGoldenCases : List RiverGoldenCase := [
${allCases.map(leanCase).join(",\n")}
]
`;

writeFileSync(leanPath, lean);
console.log(`Wrote ${leanPath}: ${allCases.length} cases`);
